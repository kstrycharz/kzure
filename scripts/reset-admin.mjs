import{readFileSync,writeFileSync}from'node:fs';
import{resolve}from'node:path';
import{randomBytes}from'node:crypto';
import{spawnSync}from'node:child_process';
const root=resolve(import.meta.dirname,'..'),envPath=resolve(root,'.env');
let text=readFileSync(envPath,'utf8');
const config=Object.fromEntries(text.split(/\r?\n/).filter(l=>l.includes('=')).map(l=>{const i=l.indexOf('=');return[l.slice(0,i),l.slice(i+1)]}));
const password=randomBytes(24).toString('base64url');
text=text.replace(/^KZURE_ADMIN_PASSWORD=.*$/m,'KZURE_ADMIN_PASSWORD='+password);
writeFileSync(envPath,text);
const reset=spawnSync('docker',['compose','run','--rm','--no-deps','-T','api','reset-admin'],{cwd:root,encoding:'utf8',windowsHide:true});
if(reset.status!==0){console.error('Administrator reset failed. Check the platform database and operator CLI.');process.exit(1)}
const url='http://localhost:'+(config.KZURE_PORT||'8088');
const response=await fetch(url+'/api/login',{method:'POST',headers:{'Content-Type':'application/json','X-Kzure-Request':'portal'},body:JSON.stringify({email:config.KZURE_ADMIN_EMAIL,password})});
if(response.status!==200){console.error('Password reset completed but sign-in verification failed: HTTP '+response.status);process.exit(1)}
const credentials=`Kzure local administrator\n\nPortal: ${url}\nEmail: ${config.KZURE_ADMIN_EMAIL}\nPassword: ${password}\n\nKeep this file private. Generated by scripts/reset-admin.mjs.\n`;
writeFileSync(resolve(root,'.local/admin-credentials.txt'),credentials);
// Do not leave the verification login active.
const cookie=response.headers.get('set-cookie')?.split(';')[0];if(cookie)await fetch(url+'/api/logout',{method:'POST',headers:{Cookie:cookie,'X-Kzure-Request':'portal','Content-Type':'application/json'},body:'{}'});
console.log('Administrator password reset and sign-in verified. New credentials are in .local/admin-credentials.txt.');
